    `DuplicateLinkedCount` INT UNSIGNED NOT NULL DEFAULT 0,
    `DeletedCount` INT UNSIGNED NOT NULL DEFAULT 0,
    `IgnoredDeletionCount` INT UNSIGNED NOT NULL DEFAULT 0,
    `UnchangedCount` INT UNSIGNED NOT NULL DEFAULT 0,
