    UNIQUE KEY `Ux_ManifestImport_PublicId` (`PublicId`),
    UNIQUE KEY `Ux_ManifestImport_User_Idempotency` (`UserId`, `IdempotencyKey`),
    UNIQUE KEY `Ux_ManifestImport_User_Source_Snapshot` (`UserId`, `MediaSourceId`, `SnapshotId`),
    UNIQUE KEY `Ux_ManifestImport_User_Source_Active` (`UserId`, `MediaSourceId`, `ActiveMarker`),
    UNIQUE KEY `Ux_ManifestImport_User_Id` (`UserId`, `Id`),
    KEY `Ix_ManifestImport_Status_NextAttempt` (`Status`, `NextAttemptAtUtc`, `Id`),
    KEY `Ix_ManifestImport_User_Source_Created` (`UserId`, `MediaSourceId`, `CreatedAtUtc`),
    CONSTRAINT `Fk_ManifestImport_MediaSource`
        FOREIGN KEY (`UserId`, `MediaSourceId`) REFERENCES `MediaSource` (`UserId`, `Id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

